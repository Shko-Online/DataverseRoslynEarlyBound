    private static string EmitOptionSet(EarlyBoundModel model, OptionSetModel optionSet, EmitOptions options)
    {
        var settings = model.Settings;
        var w = Begin(model);
        w.Line("namespace " + model.Namespace);
        w.Open();
        w.Summary(optionSet.Definition.Description ?? optionSet.Definition.DisplayName);
        w.Line("[System.Runtime.Serialization.DataContractAttribute()]");
        GeneratedCode(w, settings, options);
        w.Line($"{Visibility(settings)} enum {optionSet.EnumName}");
        w.Open();
        var first = true;
        foreach (var option in optionSet.Options)
        {
            if (!first)
            {
                w.Line();
            }

            first = false;
            var definition = option.Definition;
            w.Summary(definition.Description);
            w.Line("[System.Runtime.Serialization.EnumMemberAttribute()]");
            if (settings.AddOptionSetMetadataAttribute)
            {
                w.Line(OptionSetMetadata(option));
            }

            w.Line($"{option.MemberName} = {definition.Value.ToString(CultureInfo.InvariantCulture)},");
        }

        w.Close();
        w.Close();
        return w.ToString();
    }

    private static string OptionSetMetadata(OptionModel option)
    {
        var definition = option.Definition;
        var arguments = new List<string>
        {
            CodeWriter.Literal(definition.Label ?? string.Empty),
            option.DisplayIndex.ToString(CultureInfo.InvariantCulture),
        };

        // Trailing arguments are optional; everything up to the last one present is written.
        var optional = new[] { definition.Color, definition.Description, definition.ExternalValue };
        var last = Array.FindLastIndex(optional, v => !string.IsNullOrEmpty(v));
        for (var i = 0; i <= last; i++)
        {
            arguments.Add(string.IsNullOrEmpty(optional[i]) ? "null" : CodeWriter.Literal(optional[i]));
        }

        return $"[{EarlyBoundModelBuilder.OptionSetMetadataAttributeName}({string.Join(", ", arguments)})]";
    }

