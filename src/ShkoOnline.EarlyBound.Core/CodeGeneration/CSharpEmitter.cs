        if (!hasId && !string.IsNullOrEmpty(entity.Definition.PrimaryIdAttribute))
        {
            w.Line($"public const string Id = {CodeWriter.Literal(entity.Definition.PrimaryIdAttribute)};");
        }

        w.Close();
