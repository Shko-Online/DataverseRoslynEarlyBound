    private static void EmitAttribute(CodeWriter w, EntityModel entity, AttributeModel attribute, GeneratorSettings settings)
    {
        var definition = attribute.Definition;
        var logicalName = CodeWriter.Literal(definition.LogicalName);

        w.Line();
        w.Summary(definition.Description ?? definition.DisplayName);
        w.Line($"[Microsoft.Xrm.Sdk.AttributeLogicalNameAttribute({logicalName})]");
        if (attribute.IsObsolete)
        {
            w.Line("[System.ObsoleteAttribute()]");
        }

        var isVirtual = attribute.Kind == AttributeKind.Enum || attribute.Kind == AttributeKind.MultiEnum;
        w.Line($"public {(isVirtual ? "virtual " : string.Empty)}{attribute.TypeName} {attribute.PropertyName}");
        w.Open();

        NonUserCode(w, settings);
        w.Line("get");
        w.Open();
        switch (attribute.Kind)
        {
            case AttributeKind.Enum:
                w.Line($"return (({attribute.TypeName})({EarlyBoundModelBuilder.OptionSetEnumHelperName}.GetEnum(this, {logicalName})));");
                break;
            case AttributeKind.MultiEnum:
                w.Line($"return {EarlyBoundModelBuilder.OptionSetEnumHelperName}.GetMultiEnum<{attribute.OptionSet!.EnumName}>(this, {logicalName});");
                break;
            case AttributeKind.EntityCollection:
                w.Line($"Microsoft.Xrm.Sdk.EntityCollection collection = this.GetAttributeValue<Microsoft.Xrm.Sdk.EntityCollection>({logicalName});");
                w.Line("if (((collection != null)");
                w.Line("\t\t\t&& (collection.Entities != null)))");
                w.Open();
                w.Line($"return System.Linq.Enumerable.Cast<{attribute.ElementEntity!.ClassName}>(collection.Entities);");
                w.Close();
                w.Line("else");
                w.Open();
                w.Line("return null;");
                w.Close();
                break;
            case AttributeKind.FormattedValue:
                var parent = CodeWriter.Literal(definition.AttributeOf);
                w.Line($"if (this.FormattedValues.Contains({parent}))");
                w.Open();
                w.Line($"return this.FormattedValues[{parent}];");
                w.Close();
                w.Line("else");
                w.Open();
                w.Line("return default(string);");
                w.Close();
                break;
            default:
                w.Line($"return this.GetAttributeValue<{attribute.TypeName}>({logicalName});");
                break;
        }

        w.Close();

        if (attribute.HasSetter)
        {
            NonUserCode(w, settings);
            w.Line("set");
            w.Open();
            switch (attribute.Kind)
            {
                case AttributeKind.PrimaryId:
                    w.Line($"this.SetAttributeValue({logicalName}, value);");
                    w.Line("if (value.HasValue)");
                    w.Open();
                    w.Line("base.Id = value.Value;");
                    w.Close();
                    w.Line("else");
                    w.Open();
                    w.Line("base.Id = System.Guid.Empty;");
                    w.Close();
                    break;
                case AttributeKind.Enum:
                    w.Line($"this.SetAttributeValue({logicalName}, value.HasValue ? new Microsoft.Xrm.Sdk.OptionSetValue((int)value) : null);");
                    break;
                case AttributeKind.MultiEnum:
                    w.Line($"this.SetAttributeValue({logicalName}, {EarlyBoundModelBuilder.OptionSetEnumHelperName}.GetMultiEnum(this, {logicalName}, value));");
                    break;
                case AttributeKind.EntityCollection:
                    w.Line("if ((value == null))");
                    w.Open();
                    w.Line($"this.SetAttributeValue({logicalName}, value);");
                    w.Close();
                    w.Line("else");
                    w.Open();
                    w.Line($"this.SetAttributeValue({logicalName}, new Microsoft.Xrm.Sdk.EntityCollection(new System.Collections.Generic.List<Microsoft.Xrm.Sdk.Entity>(value)));");
                    w.Close();
                    break;
                default:
                    w.Line($"this.SetAttributeValue({logicalName}, value);");
                    break;
            }

            w.Close();
        }

        w.Close();

        if (attribute.Kind == AttributeKind.PrimaryId)
        {
            w.Line();
            w.Line($"[Microsoft.Xrm.Sdk.AttributeLogicalNameAttribute({logicalName})]");
            w.Line("public override System.Guid Id");
            w.Open();
            NonUserCode(w, settings);
            w.Line("get");
            w.Open();
            w.Line("return base.Id;");
            w.Close();
            NonUserCode(w, settings);
            w.Line("set");
            w.Open();
            w.Line($"this.{attribute.PropertyName} = value;");
            w.Close();
            w.Close();
        }
    }

    private static void EmitRelationship(CodeWriter w, RelationshipModel relationship, GeneratorSettings settings)
    {
        var schemaName = CodeWriter.Literal(relationship.Definition.SchemaName);
        var related = relationship.Related.ClassName;
        var role = relationship.Role == RelationshipRole.None
            ? "null"
            : "Microsoft.Xrm.Sdk.EntityRole." + relationship.Role;
        var roleArgument = relationship.Role == RelationshipRole.None ? string.Empty : ", " + role;

        w.Line();
        switch (relationship.Kind)
        {
            case RelationshipKind.ManyToOne:
                w.Summary("N:1 " + relationship.Definition.SchemaName);
                if (!string.IsNullOrEmpty(relationship.Definition.Attribute))
                {
                    w.Line($"[Microsoft.Xrm.Sdk.AttributeLogicalNameAttribute({CodeWriter.Literal(relationship.Definition.Attribute)})]");
                }

                break;
            case RelationshipKind.OneToMany:
                w.Summary("1:N " + relationship.Definition.SchemaName);
                break;
            default:
                w.Summary("N:N " + relationship.Definition.SchemaName);
                break;
        }

        w.Line($"[Microsoft.Xrm.Sdk.RelationshipSchemaNameAttribute({schemaName}{roleArgument})]");

        var single = relationship.Kind == RelationshipKind.ManyToOne;
        var type = single ? related : $"System.Collections.Generic.IEnumerable<{related}>";
        var getter = single ? "GetRelatedEntity" : "GetRelatedEntities";
        var setter = single ? "SetRelatedEntity" : "SetRelatedEntities";

        w.Line($"public {type} {relationship.PropertyName}");
        w.Open();
        NonUserCode(w, settings);
        w.Line("get");
        w.Open();
        w.Line($"return this.{getter}<{related}>({schemaName}, {role});");
        w.Close();
        if (relationship.HasSetter)
        {
            NonUserCode(w, settings);
            w.Line("set");
            w.Open();
            w.Line($"this.{setter}<{related}>({schemaName}, {role}, value);");
            w.Close();
        }

        w.Close();
    }

    private static void EmitAnonymousTypeConstructor(CodeWriter w, EntityModel entity, GeneratorSettings settings)
    {
        var primaryId = entity.Definition.PrimaryIdAttribute;

        w.Line();
        w.Line("/// <summary>");
        w.Line("/// Constructor for populating via LINQ queries given a LINQ anonymous type");
        w.Line("/// <param name=\"anonymousType\">LINQ anonymous type.</param>");
        w.Line("/// </summary>");
        NonUserCode(w, settings);
        w.Line($"public {entity.ClassName}(object anonymousType) : ");
        w.Line("\t\tthis()");
        w.Open();
        w.Line("foreach (var p in anonymousType.GetType().GetProperties())");
        w.Open();
        w.Line("var value = p.GetValue(anonymousType, null);");
        w.Line("var name = p.Name.ToLower();");
        w.Line();
        w.Line("if (value != null && name.EndsWith(\"enum\") && value.GetType().BaseType == typeof(System.Enum))");
        w.Open();
        w.Line("value = new Microsoft.Xrm.Sdk.OptionSetValue((int) value);");
        w.Line("name = name.Remove(name.Length - \"enum\".Length);");
        w.Close();
        w.Line("else if (value != null && value.GetType().BaseType == typeof(System.Enum))");
        w.Open();
        w.Line("value = new Microsoft.Xrm.Sdk.OptionSetValue((int) value);");
        w.Close();
        w.Line();
        w.Line("switch (name)");
        w.Open();
        w.Line("case \"id\":");
        w.Line("\tbase.Id = (System.Guid)value;");
        if (!string.IsNullOrEmpty(primaryId))
        {
            w.Line($"\tAttributes[{CodeWriter.Literal(primaryId)}] = base.Id;");
        }

        w.Line("\tbreak;");
        if (!string.IsNullOrEmpty(primaryId) && primaryId != "id")
        {
            w.Line($"case {CodeWriter.Literal(primaryId)}:");
            w.Line("\tvar id = (System.Nullable<System.Guid>) value;");
            w.Line("\tif(id == null){ continue; }");
            w.Line("\tbase.Id = id.Value;");
            w.Line("\tAttributes[name] = base.Id;");
            w.Line("\tbreak;");
        }

        w.Line("case \"formattedvalues\":");
        w.Line("\t// Add Support for FormattedValues");
        w.Line("\tFormattedValues.AddRange((Microsoft.Xrm.Sdk.FormattedValueCollection)value);");
        w.Line("\tbreak;");
        w.Line("default:");
        w.Line("\tAttributes[name] = value;");
        w.Line("\tbreak;");
        w.Close();
        w.Close();
        w.Close();
    }

