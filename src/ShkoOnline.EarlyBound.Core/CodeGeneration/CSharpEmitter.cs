        if (!settings.SuppressGeneratedCodeAttribute)
        {
            w.Line($"[System.CodeDom.Compiler.GeneratedCodeAttribute({CodeWriter.Literal(ToolName)}, {CodeWriter.Literal(options.ToolVersion)})]");
        }
    }

    private static void NonUserCode(CodeWriter w, GeneratorSettings settings)
    {
        if (settings.AddDebuggerNonUserCode)
