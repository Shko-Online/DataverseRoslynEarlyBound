    private static string EmitServiceContext(EarlyBoundModel model, string contextName, EmitOptions options)
    {
        var settings = model.Settings;
        var w = Begin(model);
        w.Line("namespace " + model.Namespace);
        w.Open();
        w.Summary("Represents a source of entities bound to a Dataverse service. It tracks and manages changes made to the retrieved entities.");
        GeneratedCode(w, settings, options);
        w.Line($"{Visibility(settings)} partial class {contextName} : Microsoft.Xrm.Sdk.Client.OrganizationServiceContext");
        w.Open();
        w.Line();
        w.Summary("Constructor.");
        NonUserCode(w, settings);
        w.Line($"public {contextName}(Microsoft.Xrm.Sdk.IOrganizationService service) : ");
        w.Line("\t\tbase(service)");
        w.Open().Close();

        foreach (var entity in model.Entities)
