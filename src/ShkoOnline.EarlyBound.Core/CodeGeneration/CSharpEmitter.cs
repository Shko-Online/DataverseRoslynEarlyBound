/// <summary>One generated C# file.</summary>
public sealed class GeneratedSource
{
    public GeneratedSource(string hintName, string text)
    {
        HintName = hintName;
        Text = text;
    }

    /// <summary>Unique file name, e.g. <c>Entities.Account.g.cs</c>.</summary>
    public string HintName { get; }

    public string Text { get; }
}

/// <summary>Facts about the consuming project that change what can be generated.</summary>
public sealed class EmitOptions
{
    /// <summary>False when the referenced SDK has no OrganizationServiceContext, so no context can be generated.</summary>
    public bool HasOrganizationServiceContext { get; set; } = true;

    /// <summary>False when the project already declares <c>[assembly: ProxyTypesAssembly]</c>.</summary>
    public bool EmitProxyTypesAssemblyAttribute { get; set; } = true;

    /// <summary>Version written into GeneratedCodeAttribute when that attribute is enabled.</summary>
    public string ToolVersion { get; set; } = "1.0.0";
}

